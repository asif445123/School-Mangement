import { test, expect } from '@playwright/test';

test('school can edit charges, preview image and manage payment accounts', async ({ page }) => {
  test.skip(!process.env.E2E_EMAIL || !process.env.E2E_PASSWORD, 'Set E2E_EMAIL and E2E_PASSWORD for a seeded test school');
  test.skip(process.env.E2E_ALLOW_MUTATIONS !== '1', 'Use a disposable test school and set E2E_ALLOW_MUTATIONS=1');
  await page.addInitScript(() => localStorage.setItem('sms-install-dismissed-at', String(Date.now() + 86400000)));
  await page.goto('/login');
  await page.getByPlaceholder('Email').fill(process.env.E2E_EMAIL!);
  await page.getByPlaceholder('Password', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await expect(page).toHaveURL(/dashboard/);
  await page.goto('/students');
  await expect(page.getByRole('columnheader', { name: 'WhatsApp', exact: true })).toBeVisible();
  await page.goto('/fees');
  await expect(page.getByText(process.env.E2E_STUDENT || 'Ali Raza', { exact: true })).toBeVisible();
  await page.getByTitle('Edit admission fee, annual charges and fees').first().click();
  await expect(page.getByRole('dialog', { name: /Edit chalan/ })).toContainText('Admission fee (Rs)');
  await expect(page.getByRole('dialog', { name: /Edit chalan/ })).toContainText('Annual charges (Rs)');
  await page.getByLabel('Admission fee (Rs)').fill('700');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByRole('dialog', { name: /Edit chalan/ })).toHaveCount(0);
  await expect(page.getByRole('cell', { name: 'Rs 700', exact: true })).toBeVisible();
  await page.getByTitle('Preview / send WhatsApp image').first().click();
  await expect(page.getByRole('dialog', { name: 'Send fee chalan on WhatsApp' })).toContainText('Using student phone number as WhatsApp.');
  await expect(page.getByRole('button', { name: 'Send image via WhatsApp' })).toBeDisabled();
  const img = page.getByRole('img', { name: /Fee chalan/ });
  await expect(img).toBeVisible();
  await expect.poll(() => img.evaluate((el: HTMLImageElement) => el.naturalWidth)).toBeGreaterThan(500);
  await page.screenshot({ path: test.info().outputPath('whatsapp-voucher.png'), fullPage: true });
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'User menu' }).click();
  await page.getByRole('button', { name: 'Payment accounts', exact: true }).click();
  await expect(page.getByText(process.env.E2E_PAYMENT_ACCOUNT || 'School Fees Collection', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add account', exact: true }).click();
  await page.getByLabel('Account type').selectOption('raast');
  const accountTitle = `School Raast ${Date.now()}`;
  await page.getByLabel('Account title', { exact: false }).fill(accountTitle);
  await page.getByLabel('Account number / mobile number / Raast ID').fill('school@bank');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText(accountTitle, { exact: true })).toBeVisible();
  await page.goto('/whatsapp-settings');
  await expect(page.getByRole('heading', { name: 'WhatsApp settings', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/fees');
  await expect(page.getByRole('heading', { name: 'Fee Chalan & Receiving' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy();
});
